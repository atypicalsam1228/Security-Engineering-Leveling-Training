def L(*lines: str) -> str:
    return "\n".join(lines)


def FILE(name: str, body: str) -> str:
    """A heredoc block that writes one file in the module folder (quoted EOF keeps every $ literal)."""
    return L("cd /workspace/cps-3", f"cat > {name} <<'EOF'", body, "EOF", f"wc -l {name}")


def HEREDOC(name: str, body: str) -> str:
    """The heredoc lines only (no cd, no line count), for blocks that also run commands."""
    return L(f"cat > {name} <<'EOF'", body, "EOF", f'test -s {name} || echo "EMPTY: type the block again"')


